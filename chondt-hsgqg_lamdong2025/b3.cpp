const ll mod = 1e9 + 7;

ll bpow(ll a, ll n, ll mod) {
	a %= mod;
	ll res = 1;
	while (n != 0) {
		if (n % 2)res = res * a % mod;
		a = a * a % mod;
		n /= 2;
	}
	return res;
}

